export const pageOf = (slug: string) => PAGES.find((p) => p.slug === slug);

export function neighbours(slug: string): { prev: DocMeta | null; next: DocMeta | null } {
  const i = PAGES.findIndex((p) => p.slug === slug);
  return { prev: i > 0 ? PAGES[i - 1] : null, next: i >= 0 && i < PAGES.length - 1 ? PAGES[i + 1] : null };
}

/** A link from one docs page to another. Every page sits one level deep (/docs/<slug> here, /<slug> on
 * docs.playpetri.xyz), so a relative href resolves correctly on both hosts. */
export const docHref = (slug: string, hash?: string) => `${slug}${hash ? `#${hash}` : ""}`;
